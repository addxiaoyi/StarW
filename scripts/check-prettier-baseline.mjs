import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const baselinePath = path.join(root, "docs", "engineering", "PRETTIER-BASELINE.txt");
const pattern = "packages/*/src/**/*.{ts,tsx}";

const result = spawnSync("bun", ["x", "prettier", "--list-different", pattern], {
  cwd: root,
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
});

if (result.error) {
  console.error("Unable to run Prettier:", result.error.message);
  process.exit(2);
}
if (result.status !== 0 && result.status !== 1) {
  process.stderr.write(result.stderr ?? "");
  process.exit(result.status ?? 2);
}

const normalize = (value) => value.trim().replaceAll("\\", "/");
const current = new Set(
  (result.stdout ?? "")
    .split(/\r?\n/)
    .map(normalize)
    .filter(Boolean)
    .sort(),
);

function fileHash(relativePath) {
  const content = fs.readFileSync(path.join(root, relativePath));
  return createHash("sha256").update(content).digest("hex");
}

if (process.argv.includes("--update")) {
  fs.mkdirSync(path.dirname(baselinePath), { recursive: true });
  const header = [
    "# Known Prettier debt baseline with source SHA-256 hashes.",
    "# Generated by `node scripts/check-prettier-baseline.mjs --update`.",
    "# New unformatted files and edits to known unformatted files fail presubmit.",
    "# Remove an entry after formatting that file.",
    "",
  ];
  const entries = [...current].map((file) => `${fileHash(file)} ${file}`);
  fs.writeFileSync(baselinePath, `${header.join("\n")}${entries.join("\n")}\n`);
  console.log(`Updated Prettier baseline: ${current.size} file(s).`);
  process.exit(0);
}

if (!fs.existsSync(baselinePath)) {
  console.error(`Prettier baseline is missing: ${path.relative(root, baselinePath)}`);
  console.error("Run the checker with --update to capture the current baseline.");
  process.exit(2);
}

const baseline = new Map();
for (const rawLine of fs.readFileSync(baselinePath, "utf8").split(/\r?\n/)) {
  const line = rawLine.trim();
  if (!line || line.startsWith("#")) continue;
  const separator = line.indexOf(" ");
  if (separator !== 64) {
    console.error(`Invalid Prettier baseline entry: ${line}`);
    process.exit(2);
  }
  baseline.set(normalize(line.slice(separator + 1)), line.slice(0, separator));
}

const newIssues = [...current].filter((file) => !baseline.has(file));
const changedIssues = [...current].filter(
  (file) => baseline.has(file) && baseline.get(file) !== fileHash(file),
);
const resolved = [...baseline.keys()].filter((file) => !current.has(file));

if (newIssues.length > 0 || changedIssues.length > 0) {
  if (newIssues.length > 0) {
    console.error("New unformatted files:");
    for (const file of newIssues) console.error(`- ${file}`);
  }
  if (changedIssues.length > 0) {
    console.error("Modified files with known formatting debt:");
    for (const file of changedIssues) console.error((`- ${file}`));
  }
  console.error("Run Prettier on the files above before submitting.");
  process.exit(1);
}

console.log(
  `Prettier baseline passed: ${current.size} known unformatted file(s), ${resolved.length} resolved baseline entry(s).`,
);
